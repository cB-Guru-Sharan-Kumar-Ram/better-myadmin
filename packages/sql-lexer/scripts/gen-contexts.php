<?php
/**
 * Dumps the keyword tables of every phpmyadmin/sql-parser context class
 * (src/Contexts/*.php) to packages/sql-lexer/src/contexts/generated/*.ts.
 *
 * Usage: php packages/sql-lexer/scripts/gen-contexts.php [/path/to/sql-parser]
 *
 * pma: vendor/phpmyadmin/sql-parser/src/Contexts/*.php::KEYWORDS
 */

declare(strict_types=1);

$root = $argv[1] ?? '/home/user/ref/sql-parser';
require $root . '/vendor/autoload.php';

$outDir = dirname(__DIR__) . '/src/contexts/generated';
@mkdir($outDir, 0777, true);
foreach (glob($outDir . '/*.ts') as $old) {
    unlink($old);
}

$names = [];
foreach (glob($root . '/src/Contexts/Context*.php') as $file) {
    $name = substr(basename($file, '.php'), strlen('Context'));
    $class = 'PhpMyAdmin\\SqlParser\\Contexts\\Context' . $name;
    $keywords = $class::KEYWORDS;

    // Group keywords by flags, keeping PHP's declaration order inside each group.
    $groups = [];
    foreach ($keywords as $kw => $flags) {
        $groups[$flags][] = $kw;
    }
    ksort($groups);

    $lines = [];
    $lines[] = '// Generated by packages/sql-lexer/scripts/gen-contexts.php. Do not edit.';
    $lines[] = '// pma: vendor/phpmyadmin/sql-parser/src/Contexts/Context' . $name . '.php::KEYWORDS';
    $lines[] = '// Keywords grouped by flags; inside a group they are separated by "|" (keywords may contain spaces).';
    $lines[] = 'export const keywords: Readonly<Record<number, string>> = {';
    foreach ($groups as $flags => $list) {
        $lines[] = '  ' . $flags . ': ' . json_encode(implode('|', $list), JSON_UNESCAPED_SLASHES) . ',';
    }
    $lines[] = '}';
    $lines[] = 'export const count = ' . count($keywords);
    file_put_contents($outDir . '/' . $name . '.ts', implode("\n", $lines) . "\n");
    $names[] = $name;
}

sort($names);
$idx = [];
$idx[] = '// Generated by packages/sql-lexer/scripts/gen-contexts.php. Do not edit.';
foreach ($names as $name) {
    $idx[] = 'import * as ' . $name . " from './" . $name . ".ts'";
}
$idx[] = '';
$idx[] = 'export const generatedContexts = {';
foreach ($names as $name) {
    $idx[] = '  ' . $name . ',';
}
$idx[] = '} as const';
$idx[] = '';
$idx[] = 'export type ContextName = keyof typeof generatedContexts';
file_put_contents($outDir . '/index.ts', implode("\n", $idx) . "\n");

echo 'Generated ' . count($names) . " contexts\n";
