/**
 * pnpm i18n:import — imports phpMyAdmin's gettext catalogues and language table.
 *
 * Reads `$PMA_ROOT/resources/po/*.po` (phpMyAdmin's git tree, the same files Weblate commits) and writes
 *   - po/<code>.po                 the entries msgfmt compiles into the .mo phpMyAdmin loads (non-fuzzy,
 *                                  every msgstr filled, no obsolete `#~`), comments stripped. Only the
 *                                  locales a release ships: bin/remove-incomplete-mo deletes every .mo
 *                                  below 40 % translated (msgfmt --statistics) and LanguageManager only
 *                                  offers locales whose .mo exists.
 *   - src/generated/catalog-index.ts   translation statistics, shipped locales, source commit
 *   - src/generated/languages.ts       LanguageManager::$languageData (via scripts/dump-languages.php)
 *
 * Catalogues are compiled from po/ at build time (vite plugin) or on first use (server), see compile.ts.
 * Usage: PMA_ROOT=/path/to/phpmyadmin pnpm i18n:import
 */
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { formatPo } from '../src/compile.ts'
import { isCompiled, parsePo, poStatistics } from '../src/po.ts'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = resolve(here, '..')
// ../ref sits next to the main checkout, which a linked worktree is not: resolve it from git's common dir
const mainCheckout = dirname(
  resolve(pkg, execFileSync('git', ['rev-parse', '--git-common-dir'], { cwd: pkg, encoding: 'utf8' }).trim()),
)
const pmaRoot = resolve(process.env.PMA_ROOT ?? join(mainCheckout, '../ref/pma'))
const poDir = join(pmaRoot, 'resources/po')
const outDir = join(pkg, 'po')
/** bin/remove-incomplete-mo THRESHOLD */
const THRESHOLD = 40

const git = (...args: string[]) => {
  try {
    return execFileSync('git', ['-C', pmaRoot, ...args], { encoding: 'utf8' }).trim()
  } catch {
    return 'unknown'
  }
}
const commit = git('rev-parse', 'HEAD')
const poCommit = git('log', '-1', '--format=%H', '--', 'resources/po')

const files = readdirSync(poDir)
  .filter((f) => f.endsWith('.po'))
  .sort()
if (files.length === 0) throw new Error(`No .po files in ${poDir}`)
rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const pot = parsePo(readFileSync(join(poDir, 'phpmyadmin.pot'), 'utf8'))
// the template (msgids only) for `pnpm i18n:parity`
writeFileSync(
  join(outDir, 'phpmyadmin.pot'),
  formatPo(
    pot.headerRaw,
    pot.entries,
    `Imported from phpMyAdmin ${commit} resources/po/phpmyadmin.pot by packages/i18n/scripts/import-po.ts.`,
  ),
)
const stats: Record<string, number> = {}
const shipped: string[] = []
let shippedMessages = 0
for (const file of files) {
  const code = file.slice(0, -3)
  const po = parsePo(readFileSync(join(poDir, file), 'utf8'))
  const st = poStatistics(po)
  const percent = Math.floor((100 * st.translated) / (st.translated + st.fuzzy + st.untranslated))
  stats[code] = percent
  if (percent < THRESHOLD) {
    console.log(`${code}: ${percent}% — not shipped`)
    continue
  }
  const entries = po.entries.filter(isCompiled)
  shipped.push(code)
  shippedMessages += entries.length
  writeFileSync(
    join(outDir, `${code}.po`),
    formatPo(
      po.headerRaw,
      entries,
      `Imported from phpMyAdmin ${commit} resources/po/${file} by packages/i18n/scripts/import-po.ts.\nOnly the entries msgfmt compiles are kept; edit translations upstream (Weblate), not here.`,
    ),
  )
  console.log(`${code}: ${entries.length} messages, ${percent}%`)
}

const languages = JSON.parse(
  execFileSync('php', [join(here, 'dump-languages.php'), pmaRoot], { encoding: 'utf8' }),
) as unknown[]

const header = `// Generated by packages/i18n/scripts/import-po.ts — do not edit.
// Source: phpMyAdmin ${commit} (resources/po last changed in ${poCommit}).
`
mkdirSync(join(pkg, 'src/generated'), { recursive: true })
writeFileSync(
  join(pkg, 'src/generated/catalog-index.ts'),
  `${header}
/** Translation percentage per catalogue (pma: app/language_stats.inc.php, written by bin/remove-incomplete-mo). */
export const languageStats: Readonly<Record<string, number>> = ${JSON.stringify(stats, null, 2)}

/** Catalogues a phpMyAdmin release ships (≥ ${THRESHOLD} % translated), i.e. resources/locale/<code>. */
export const shippedLocales: readonly string[] = ${JSON.stringify(shipped)}

export const catalogSource = {
  repository: 'https://github.com/phpmyadmin/phpmyadmin',
  commit: '${commit}',
  poCommit: '${poCommit}',
  potMessages: ${pot.entries.length},
  poFiles: ${files.length},
  shippedLocales: ${shipped.length},
  shippedMessages: ${shippedMessages},
} as const
`,
)
writeFileSync(
  join(pkg, 'src/generated/languages.ts'),
  `${header}
/** [key, code, English name, native name (HTML entities decoded), match regex, MySQL lc_messages locale] */
export const languageData: ReadonlyArray<readonly [string, string, string, string, string, string]> = [
${(languages as Array<Record<string, string>>)
  .map((l) => `  ${JSON.stringify([l.key, l.code, l.english, l.native, l.regex, l.mysql])},`)
  .join('\n')}
]
`,
)
console.log(
  `${files.length} catalogues, ${shipped.length} shipped, ${shippedMessages} messages, ${pot.entries.length} pot messages`,
)
