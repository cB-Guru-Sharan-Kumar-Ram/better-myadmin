export function renderJs(cov: Coverage): string {
  return [
    ...header(
      'js',
      cov,
      "What phpMyAdmin's resources/js does in the browser: event bindings (with the keys keyboard handlers compare), confirm/alert dialogs (with their `window.Messages` keys), AJAX calls (with their routes) and CodeMirror key bindings. " +
        'Claims: `js:<script>#…` keys in `pma-controls.ts` registries (or `data-pma`), docs/architecture/12; dispositions: `tools/parity/map/js.yaml`.',
    ),
    ...perAreaSections(cov, 'js', (items) => {
      const byScript = groupBy(items, (i) => i.key.slice(3, i.key.indexOf('#')))
      return [
        table(
          ['Script', 'Covered', 'Not covered'],
          [...byScript.entries()]
            .sort((a, b) => a[0].localeCompare(b[0]))
            .map(([f, its]) => {
              const done = its.filter((i) => COVERED.has(i.status))
              const notDone = its.filter((i) => !COVERED.has(i.status))
              const show = (i: ItemCoverage) =>
                `${STATUS_ICON[i.status]} ${code(i.label.length > 80 ? `${i.label.slice(0, 77)}…` : i.label)}`
              return [
                code(f),
                `${done.length}/${its.length}${done.length > 0 ? `: ${done.map(show).join(' ')}` : ''}`,
                notDone.map(show).join(' '),
              ]
            }),
        ),
      ]
    }),
  ].join('\n')
}

export function renderMessages(cov: Coverage, inv: Inventories, perFile = 12): string {
  const refs = new Map(inv.messages.items.map((m) => [m.key, m.refs]))
  return [
    ...header(
      'messages',
      cov,
      "Every msgid of phpMyAdmin's catalogue, attributed to the templates/PHP/JS files that use it. A msgid our code never translates usually " +
        'means the feature around it is missing: this is the "likely missing features" list, per area and source file (largest gaps first). ' +
        'Dispositions: `tools/parity/map/messages.yaml`.',
    ),
    ...perAreaSections(cov, 'messages', (items) => {
      const missing = items.filter((i) => !COVERED.has(i.status))
      const byFile = new Map<string, { total: number; unused: ItemCoverage[] }>()
      for (const it of items) {
        for (const f of effectiveFiles(refs.get(it.key) ?? [])) {
          const e = byFile.get(f) ?? { total: 0, unused: [] }
          e.total++
          if (!COVERED.has(it.status)) e.unused.push(it)
          byFile.set(f, e)
        }
      }
      const rows = [...byFile.entries()]
        .filter(([, e]) => e.unused.length > 0)
        .sort((a, b) => b[1].unused.length - a[1].unused.length || a[0].localeCompare(b[0]))
        .map(([f, e]) => [
          code(f),
          `${e.unused.length}/${e.total}`,
          e.unused
            .slice(0, perFile)
            .map((i) => code(i.label.length > 70 ? `${i.label.slice(0, 67)}…` : i.label))
            .join(' · ') + (e.unused.length > perFile ? ` · … +${e.unused.length - perFile}` : ''),
        ])
      return [
        `${missing.length} msgids not used yet.`,
        '',
        table(['Source file', 'Unused / total', 'Unused msgids'], rows),
      ]
    }),
  ].join('\n')
}

export function renderChecklist(cov: Coverage): string {
  return [
    ...header(
      'checklist',
      cov,
      'Every `- [ ]` item of docs/features/*.md. A test links to an item when its title contains the item id (e.g. `p01-3f9a2c`) or the exact item text; ' +
        'status comes from the latest results in .data/parity-results/ (`pnpm parity:report --run`), else from the doc marker.',
    ),
    ...perAreaSections(cov, 'checklist', (items) => {
      const linked = items.filter((i) => i.targets.length > 0 || i.status !== 'missing')
      return [
        `${items.filter((i) => i.status === 'missing').length} items without a linked test.`,
        '',
        ...(linked.length === 0
          ? []
          : [
              table(
                ['', 'Id', 'Item', 'Tests'],
                linked.map((it) => [
                  STATUS_ICON[it.status],
                  code(it.key),
                  cell(it.label.length > 140 ? `${it.label.slice(0, 137)}…` : it.label),
                  cell(it.targets.join('<br>')),
                ]),
              ),
            ]),
      ]
    }),
  ].join('\n')
}

