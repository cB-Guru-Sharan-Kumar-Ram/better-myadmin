/**
 * Markdown reports under docs/reference/coverage/ and the generated docs/reference/pma-route-map.md.
 * Pure functions of the coverage (no clock, no machine paths) so the output is reproducible and the
 * gate can verify it is up to date.
 */
import { type Area, loadAreaRules, loadAreas } from './areas.ts'
import {
  COVERAGE_KINDS,
  COVERED,
  type Coverage,
  type CoverageKind,
  type ItemCoverage,
  STATUSES,
  type Status,
  effectiveFiles,
} from './coverage.ts'
import type { Inventories } from './inventory.ts'
import { type Maps, list } from './maps.ts'
import { cell, code, groupBy, pct } from './util.ts'

export const GENERATED_LINE = (what: string) =>
  `<!-- Generated by \`pnpm parity:report\` (tools/parity) from ${what}. Do not edit by hand. -->`

const KIND_TITLE: Record<CoverageKind, string> = {
  routes: 'Routes',
  controls: 'Template controls',
  directives: 'Config directives',
  messages: 'Messages (msgids)',
  js: 'JS behaviours',
  checklist: 'Checklist items',
}

const STATUS_ICON: Record<Status, string> = {
  implemented: '✅',
  exception: '🔀',
  'n/a': '➖',
  planned: '🗓️',
  untested: '🧪',
  failing: '❌',
  missing: '⬜',
  broken: '💥',
}

export function milestoneOf(area: string): string {
  const rules = loadAreaRules() as { milestones?: Record<string, string> }
  return rules.milestones?.[area] ?? '—'
}

function areaName(areas: Area[], id: string): string {
  const a = areas.find((x) => x.id === id)
  return a === undefined ? id : a.id === 'other' ? 'other' : `${a.id} ${a.title}`
}

function areaLink(areas: Area[], id: string): string {
  const a = areas.find((x) => x.id === id)
  if (a?.doc == null) return areaName(areas, id)
  return `[${areaName(areas, id)}](../../${a.doc.replace(/^docs\//, '')})`
}

const frac = (items: ItemCoverage[]) => {
  const c = items.filter((i) => COVERED.has(i.status)).length
  return items.length === 0 ? '—' : `${c}/${items.length} (${pct(c, items.length)})`
}

const implFrac = (items: ItemCoverage[]) => {
  const c = items.filter((i) => i.status === 'implemented').length
  return items.length === 0 ? '—' : `${c}/${items.length}`
}

export function summaryRows(cov: Coverage): string[][] {
  return COVERAGE_KINDS.map((k) => {
    const kc = cov.kinds[k]
    return [
      KIND_TITLE[k],
      String(kc.total),
      ...STATUSES.map((s) => String(kc.counts[s])),
      String(kc.covered),
      pct(kc.covered, kc.total),
    ]
  })
}

export const SUMMARY_HEADER = ['Inventory', 'Total', ...STATUSES, 'Covered', '%']

function table(header: string[], rows: string[][]): string {
  return [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n')
}

