export function renderRouteMapDoc(inv: Inventories, maps: Maps, cov: Coverage): string {
  const status = new Map(cov.kinds.routes.items.map((i) => [i.key, i.status]))
  const app = inv.routes.items.filter((r) => r.scope === 'app')
  const setup = inv.routes.items.filter((r) => r.scope === 'setup')
  const equiv = (key: string) => {
    const e = maps.routes[key]
    if (e === undefined) return '—'
    const parts = [
      ...list(e.ui).map((u) => `UI ${code(u)}`),
      ...list(e.api).map((a) => `API ${code(a)}`),
      ...list(e.later).map((a) => `later ${code(a)}`),
    ]
    if (e['n/a'] !== undefined) parts.push(`n/a: ${cell(String(e['n/a']))}`)
    if (e.note !== undefined) parts.push(`(${cell(String(e.note))})`)
    return parts.join(' · ') || '—'
  }
  const disp = (key: string) => {
    const e = maps.routes[key]
    const s = status.get(key) ?? 'missing'
    const extra = [e?.planned, e?.exception].filter((x) => x !== undefined).join(', ')
    return `${STATUS_ICON[s]} ${s}${extra !== '' ? ` (${extra})` : ''}`
  }
  const row = (r: (typeof app)[number]) =>
    `| ${r.methods.join(', ')} | ${code(r.path)} | ${code(r.controller)} | ${equiv(r.key)} | ${disp(r.key)} |`
  return [
    GENERATED_LINE('tools/parity/inventory/routes.json and tools/parity/map/routes.yaml'),
    '',
    '# phpMyAdmin route map (source of truth for parity)',
    '',
    `Every route of phpMyAdmin ${code(inv.routes._meta.referenceCommit.slice(0, 8))}, extracted by executing its routing definition ` +
      '(`src/Routing/Routes.php::collect`, which reads the `#[Route]` attributes of every controller and feeds FastRoute) — ' +
      `${app.length} routes — plus the ${setup.length} paths of the setup script (\`Routing::callSetupController\`). ` +
      '"GET, POST" routes are page routes that also accept form posts, "POST"-only routes are AJAX actions, "GET"-only routes are read-only pages or JSON feeds.',
    '',
    'The equivalent column is the BetterMyAdmin SPA route (UI) and API endpoint that replace it (see [API reference](../architecture/05-api-reference.md) ' +
      'and [Frontend architecture](../architecture/03-frontend-architecture.md)). Edit `tools/parity/map/routes.yaml`, then run `pnpm parity:report`. ' +
      'Status is computed: targets are checked against the Hono registrations and TanStack file routes, so "implemented" means every listed target exists; ' +
      'see [coverage](coverage/routes.md).',
    '',
    '| Methods | phpMyAdmin route | Controller | BetterMyAdmin equivalent | Status |',
    '|---|---|---|---|---|',
    ...app.map(row),
    '',
    '## Setup script',
    '',
    '| Methods | Path | Controller | BetterMyAdmin equivalent | Status |',
    '|---|---|---|---|---|',
    ...setup.map(row),
    '',
  ].join('\n')
}
