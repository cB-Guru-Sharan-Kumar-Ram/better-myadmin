export interface MissingSource {
  source: string
  area: string
  routes: number
  controls: number
  msgids: number
  js: number
  score: number
}

/**
 * phpMyAdmin source files ranked by how much of them we lack: uncovered routes (×5, by controller),
 * uncovered template controls (×2) and unused msgids (×1, by referencing file).
 */
export function missingBySource(cov: Coverage, inv: Inventories): MissingSource[] {
  const m = new Map<string, MissingSource>()
  const get = (source: string, area: string) => {
    let e = m.get(source)
    if (e === undefined) {
      e = { source, area, routes: 0, controls: 0, msgids: 0, js: 0, score: 0 }
      m.set(source, e)
    }
    return e
  }
  const routeFile = new Map(inv.routes.items.map((r) => [r.key, r.file]))
  for (const it of cov.kinds.routes.items) {
    if (COVERED.has(it.status)) continue
    get(routeFile.get(it.key) ?? it.source, it.area).routes++
  }
  const controlFile = new Map(inv.controls.items.map((c) => [c.key, c.file]))
  for (const it of cov.kinds.controls.items) {
    if (COVERED.has(it.status)) continue
    get(controlFile.get(it.key) ?? it.source, it.area).controls++
  }
  const jsFile = new Map(inv.js.items.map((j) => [j.key, j.file]))
  for (const it of cov.kinds.js.items) {
    if (COVERED.has(it.status)) continue
    get(jsFile.get(it.key) ?? it.source, it.area).js++
  }
  const rules = loadAreaRules()
  const msgRefs = new Map(inv.messages.items.map((x) => [x.key, x.refs]))
  for (const it of cov.kinds.messages.items) {
    if (COVERED.has(it.status)) continue
    for (const f of effectiveFiles(msgRefs.get(it.key) ?? [])) {
      const area = Object.entries(rules.rules)
        .filter(([p]) => f.startsWith(p))
        .sort((a, b) => b[0].length - a[0].length)[0]?.[1]
      get(f, String(area ?? rules.default)).msgids++
    }
  }
  for (const e of m.values()) e.score = e.routes * 5 + e.controls * 2 + e.js * 2 + e.msgids
  return [...m.values()].sort((a, b) => b.score - a.score || a.source.localeCompare(b.source))
}

export function renderReadme(cov: Coverage, inv: Inventories, top = 30): string {
  const areas = loadAreas()
  const lines: string[] = []
  lines.push(
    GENERATED_LINE('tools/parity/inventory, tools/parity/map and a static scan of apps/ and packages/'),
  )
  lines.push('')
  lines.push('# Parity coverage')
  lines.push('')
  lines.push(
    `Mechanical inventories of phpMyAdmin \`${cov.referenceCommit.slice(0, 8)}\` ([reference-commit.txt](../reference-commit.txt)) ` +
      'and how much of each BetterMyAdmin covers. Covered = implemented + exception + n/a. ' +
      'See [Testing and parity](../../architecture/11-testing-and-parity-strategy.md#mechanical-inventories-and-the-parity-gate) for how the numbers are computed and gated.',
  )
  lines.push('')
  lines.push(table(SUMMARY_HEADER, summaryRows(cov)))
  lines.push('')
  lines.push(
    `Status: ${STATUSES.map((s) => `${STATUS_ICON[s]} ${s}`).join(' · ')}. Details: ${COVERAGE_KINDS.map((k) => `[${KIND_TITLE[k].toLowerCase()}](${k}.md)`).join(', ')}.`,
  )
  lines.push('')
  lines.push('## Per feature area')
  lines.push('')
  lines.push(
    'Covered / total per inventory (directives are attributed to the feature doc that mentions them most).',
  )
  lines.push('')
  const rows = areas.map((a) => [
    areaLink(areas, a.id),
    milestoneOf(a.id),
    ...COVERAGE_KINDS.map((k) => frac(cov.kinds[k].items.filter((i) => i.area === a.id))),
  ])
  lines.push(table(['Area', 'Milestone', ...COVERAGE_KINDS.map((k) => KIND_TITLE[k])], rows))
  lines.push('')
  lines.push(`## Top ${top} missing`)
  lines.push('')
  lines.push(
    'phpMyAdmin source files ranked by what we lack: uncovered routes (weight 5, by controller), uncovered template controls ' +
      '(weight 2), uncovered JS behaviours (weight 2) and unused msgids (weight 1, by the files that use them). Unused msgids are the best "likely missing feature" signal: ' +
      'see [messages.md](messages.md) for the strings themselves.',
  )
  lines.push('')
  lines.push(
    table(
      ['#', 'phpMyAdmin source', 'Area', 'Milestone', 'Routes', 'Controls', 'JS', 'Msgids', 'Score'],
      missingBySource(cov, inv)
        .slice(0, top)
        .map((e, i) => [
          String(i + 1),
          code(e.source),
          areaName(areas, e.area),
          milestoneOf(e.area),
          String(e.routes),
          String(e.controls),
          String(e.js),
          String(e.msgids),
          String(e.score),
        ]),
    ),
  )
  lines.push('')
  if (cov.problems.length > 0) {
    lines.push('## Problems (the gate fails on these)')
    lines.push('')
    for (const p of cov.problems) lines.push(`- ${cell(p)}`)
    lines.push('')
  }
  if (cov.notes.length > 0) {
    lines.push('## Cross-check notes')
    lines.push('')
    for (const n of cov.notes) lines.push(`- ${cell(n)}`)
    lines.push('')
  }
  if (cov.scans.unknownMsgids.length > 0) {
    lines.push('## Msgids we use that phpMyAdmin does not have')
    lines.push('')
    lines.push('Also reported by `pnpm i18n:parity` (which accepts `// i18n-new:` annotations).')
    lines.push('')
    for (const k of cov.scans.unknownMsgids) lines.push(`- ${code(k.replace('\u0004', ' | '))}`)
    lines.push('')
  }
  lines.push('## Inventories')
  lines.push('')
  lines.push(
    table(
      ['Inventory', 'Items', 'Extracted from'],
      (['routes', 'controls', 'directives', 'messages', 'js'] as const).map((k) => [
        `[${k}.json](../../../tools/parity/inventory/${k}.json)`,
        String(inv[k]._meta.count),
        cell(inv[k]._meta.source),
      ]),
    ),
  )
  lines.push('')
  lines.push(
    `Checklist items: ${cov.kinds.checklist.total} from \`docs/features/*.md\` (ids in [checklist-ids.json](../../../tools/parity/map/checklist-ids.json)). ` +
      `Our side: ${cov.scans.endpoints.length} API endpoints, ${cov.scans.spaRoutes.length} SPA routes ` +
      `(${cov.scans.spaRoutes.filter((r) => r.placeholder || r.splat).length} placeholders/catch-alls), ` +
      `${cov.scans.claims.length} control claims, ${cov.scans.tests.length} tests.`,
  )
  lines.push('')
  return lines.join('\n')
}

function detailCell(it: ItemCoverage): string {
  const parts = [it.detail, ...it.problems.map((p) => `💥 ${p}`)].filter(
    (x): x is string => x !== undefined && x !== '',
  )
  return cell(parts.join(' · '))
}

function perAreaSections(
  cov: Coverage,
  kind: CoverageKind,
  render: (items: ItemCoverage[]) => string[],
): string[] {
  const areas = loadAreas()
  const lines: string[] = []
  const byArea = groupBy(cov.kinds[kind].items, (i) => i.area)
  for (const a of areas) {
    const items = byArea.get(a.id) ?? []
    if (items.length === 0) continue
    lines.push(`## ${areaName(areas, a.id)} — ${frac(items)} covered, ${implFrac(items)} implemented`)
    lines.push('')
    lines.push(...render(items))
    lines.push('')
  }
  return lines
}

function header(kind: CoverageKind, cov: Coverage, intro: string): string[] {
  const kc = cov.kinds[kind]
  return [
    GENERATED_LINE(
      `tools/parity/inventory/${kind === 'checklist' ? '../map/checklist-ids.json' : `${kind}.json`}`,
    ),
    '',
    `# ${KIND_TITLE[kind]} coverage`,
    '',
    intro,
    '',
    `${kc.covered}/${kc.total} covered (${pct(kc.covered, kc.total)}): ${STATUSES.filter(
      (s) => kc.counts[s] > 0,
    )
      .map((s) => `${kc.counts[s]} ${s}`)
      .join(', ')}. [Summary](README.md).`,
    '',
  ]
}

export function renderRoutes(cov: Coverage): string {
  return [
    ...header(
      'routes',
      cov,
      'Every phpMyAdmin route (FastRoute collector executed, plus the setup script) and what replaces it. Mapping: `tools/parity/map/routes.yaml`.',
    ),
    ...perAreaSections(cov, 'routes', (items) => [
      table(
        ['', 'Route', 'Controller', 'Targets', 'Detail'],
        items.map((it) => [
          STATUS_ICON[it.status],
          code(it.label),
          code(it.source),
          cell(it.targets.join('<br>')),
          detailCell(it),
        ]),
      ),
    ]),
  ].join('\n')
}

export function renderControls(cov: Coverage): string {
  return [
    ...header(
      'controls',
      cov,
      'Form controls, action links and checkbox/radio groups of every Twig template. Claims: `pma-controls.ts` registries and `data-pma` attributes in apps/web (docs/architecture/12); dispositions: `tools/parity/map/controls.yaml`.',
    ),
    ...perAreaSections(cov, 'controls', (items) => {
      const byTemplate = groupBy(items, (i) => i.key.slice(0, i.key.indexOf('#')))
      return [
        table(
          ['Template', 'Covered', 'Implemented / other', 'Not covered'],
          [...byTemplate.entries()]
            .sort((a, b) => a[0].localeCompare(b[0]))
            .map(([t, its]) => {
              const local = (i: ItemCoverage) => code(i.key.slice(i.key.indexOf('#') + 1))
              const done = its.filter((i) => COVERED.has(i.status))
              const notDone = its.filter((i) => !COVERED.has(i.status))
              return [
                code(t),
                `${done.length}/${its.length}`,
                done.map((i) => `${STATUS_ICON[i.status]} ${local(i)}`).join(' '),
                notDone.map((i) => `${STATUS_ICON[i.status]} ${local(i)}`).join(' '),
              ]
            }),
        ),
      ]
    }),
  ].join('\n')
}

