import { randomInt } from 'node:crypto'
import { importPmaConfig } from '@bettermyadmin/config'
import { type PhpValue, varExportValue } from '@bettermyadmin/export'
import type { ConfigFile } from '../preferences/config-file.ts'

/**
 * The setup script's generated configuration file, byte for byte phpMyAdmin's config.inc.php
 * (with the product name in the header, X33), and the same configuration in BetterMyAdmin's
 * format (X6/X7).
 * pma: src/Setup/ConfigGenerator.php
 */

/** A decoded PHP array: a JS list for 0..n-1 keys, else a string-keyed object. */
const isArr = (v: unknown): v is Record<string, unknown> | unknown[] => v !== null && typeof v === 'object'

/** PHP's array_is_list for a decoded array. */
function isList(v: Record<string, unknown> | unknown[]): boolean {
  if (Array.isArray(v)) return true
  return Object.keys(v).every((k, i) => k === String(i))
}

/** The decoded value as the PhpValue var_export takes (objects become ordered Maps). */
function php(v: unknown): PhpValue {
  if (v === undefined || v === null) return null
  if (typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean') return v
  if (Array.isArray(v)) return v.map(php)
  if (isArr(v)) return new Map(Object.entries(v).map(([k, x]) => [k, php(x)]))
  return String(v)
}

const varExport = (v: unknown) => varExportValue(php(v))
const key = (k: string) => k.replace(/[^A-Za-z0-9_]/g, '_')

/** gmdate(DATE_RFC1123): `Mon, 12 Oct 2026 03:30:00 +0000` */
export function rfc1123(d: Date): string {
  const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat']
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
  const p = (n: number) => String(n).padStart(2, '0')
  return `${days[d.getUTCDay()]}, ${p(d.getUTCDate())} ${months[d.getUTCMonth()]} ${d.getUTCFullYear()} ${p(
    d.getUTCHours(),
  )}:${p(d.getUTCMinutes())}:${p(d.getUTCSeconds())} +0000`
}

/**
 * A 32-byte key (sodium_crypto_secretbox_keygen). Printable ASCII, so the value stays a plain
 * string in the setup session and in the BetterMyAdmin configuration.
 */
export function generateSecret(): string {
  let s = ''
  for (let i = 0; i < 32; i++) s += String.fromCharCode(randomInt(33, 127))
  return s
}

/** ConfigGenerator::getBlowfishSecretKey: the value when it is 32 bytes, else a new key. */
function blowfishKey(v: unknown): Buffer {
  if (typeof v === 'string' && Buffer.byteLength(v, 'utf8') === 32) return Buffer.from(v, 'utf8')
  return Buffer.from(generateSecret(), 'utf8')
}

/** ConfigGenerator::exportZeroBasedArray: up to 4 values on one line, else one per line. */
function zeroBased(list: unknown[], eol: string): string {
  const parts = list.map(varExport)
  if (parts.length <= 4) return `[${parts.join(', ')}]`
  return `[${eol}    ${parts.join(`,${eol}    `)}]`
}

/** ConfigGenerator::getVarExport */
function varLine(name: string, value: unknown, eol: string): string {
  if (name === 'blowfish_secret')
    return `$cfg['blowfish_secret'] = \\sodium_hex2bin('${blowfishKey(value).toString('hex')}');${eol}`
  if (!isArr(value) || (Array.isArray(value) ? value.length === 0 : Object.keys(value).length === 0))
    return `$cfg['${name}'] = ${varExport(value)};${eol}`
  if (isList(value)) return `$cfg['${name}'] = ${zeroBased(Object.values(value), eol)};${eol}`
  let ret = ''
  for (const [k, v] of Object.entries(value)) ret += `$cfg['${name}']['${key(k)}'] = ${varExport(v)};${eol}`
  return ret
}

/** ConfigGenerator::getServerPart */
function serverPart(cf: ConfigFile, eol: string, servers: Record<string, Record<string, unknown>>): string {
  if (cf.getServerCount() === 0) return ''
  let ret = `/* Servers configuration */${eol}$i = 0;${eol}${eol}`
  for (const [id, server] of Object.entries(servers)) {
    // strtr($name, '*/', '-') maps only '*' (the shorter of the two lists)
    ret += `/* Server: ${`${cf.getServerName(Number(id))} [${id}] `.replaceAll('*', '-')}*/${eol}$i++;${eol}`
    for (const [k, v] of Object.entries(server)) {
      const value = isArr(v) && isList(v) ? zeroBased(Object.values(v), eol) : varExport(v)
      ret += `$cfg['Servers'][$i]['${key(k)}'] = ${value};${eol}`
    }
    ret += eol
  }
  return `${ret}/* End of servers configuration */${eol}${eol}`
}

/** ConfigGenerator::getConfigFile */
export function generateConfigFile(
  cf: ConfigFile,
  opts: { eol: 'unix' | 'win'; version: string; date?: Date },
): string {
  const eol = opts.eol === 'win' ? '\r\n' : '\n'
  const conf = cf.getConfig()
  let ret =
    `<?php${eol}/**${eol} * Generated configuration file${eol}` +
    ` * Generated by: BetterMyAdmin ${opts.version} setup script${eol}` +
    ` * Date: ${rfc1123(opts.date ?? new Date())}${eol} */${eol}${eol}`
  const servers = conf.Servers
  if (isArr(servers) && Object.keys(servers).length > 0) {
    ret += serverPart(cf, eol, servers as Record<string, Record<string, unknown>>)
  }
  delete conf.Servers
  const persist = new Set(cf.getPersistKeys())
  for (const [k0, v] of Object.entries(conf)) {
    const k = key(k0)
    ret += varLine(k, v, eol)
    persist.delete(k)
  }
  // keep 1d array keys which are present in the persist keys
  for (const k0 of persist) {
    if (k0.includes('/')) continue
    const k = key(k0)
    ret += varLine(k, cf.getDefault(k), eol)
  }
  return ret + eol
}

/**
 * The generated file as a `bettermyadmin.config.json` (the second output): the same `$cfg` read
 * back by `bma import-pma-config`; the `sodium_hex2bin` secret is kept as its 64-digit hex string.
 */
export function generateBmaConfig(phpSource: string): string {
  const { config } = importPmaConfig(phpSource)
  return `${JSON.stringify(config, null, 2)}\n`
}
