// biome-ignore lint/suspicious/noExplicitAny: loosely typed API payloads in tests
type Json = Record<string, any>
type Msg = Pick<SetupMessage, 'id' | 'type' | 'title' | 'hidden'> & { text: string }

/** phpMyAdmin's overview (it carries the form token). */
async function pmaHome(c: PmaClient, query = ''): Promise<string> {
  const html = await c.getPage(`/setup/index.php?route=/setup${query}`)
  c.token = html.match(/name="token" value="([^"]+)"/)?.[1] ?? c.token
  return html
}
/** The fields a page's config form posts. */
async function pmaFormPairs(c: PmaClient, path: string): Promise<Pairs> {
  return serializeForm(findForm(await c.getPage(path), { cls: 'config-form' }))
}
/** submit_save of a setup form. */
const pmaSave = (c: PmaClient, path: string, pairs: Pairs): Promise<string> =>
  c.postPage(path, setPair(pairs, 'submit_save', 'Apply'))
/** submit_download of the overview's configuration file card. */
const pmaDownload = (c: PmaClient, eol: 'unix' | 'win', serverDefault = '1'): Promise<string> =>
  c.postPage('/setup/index.php?route=/setup/show-config', {
    DefaultLang: 'en',
    ServerDefault: serverDefault,
    eol,
    submit_download: 'Download',
  })

/** BetterMyAdmin's setup API, posting what the SPA's form posts. */
class BmaSetup {
  readonly t = testApp(testConfig())
  async home(query = ''): Promise<SetupOverview> {
    // the CSRF token (the SPA reads it from its cookie)
    if (this.t.jar.size === 0) await this.t.req('GET', '/api/auth/state')
    return (await this.t.req('GET', `/api/setup${query}`)).json as unknown as SetupOverview
  }
  /** a submit; like phpMyAdmin's redirect, a saved form goes back to the overview */
  async post(path: string, pairs: Pairs): Promise<SetupSaveResponse> {
    const r = await this.postOnly(path, pairs)
    if (r.saved) await this.home()
    return r
  }
  async postOnly(path: string, pairs: Pairs): Promise<SetupSaveResponse> {
    const values: Record<string, string | string[]> = {}
    for (const [k, v] of pairs) {
      const cur = values[k]
      values[k] = cur === undefined ? v : Array.isArray(cur) ? [...cur, v] : [cur, v]
    }
    return (await this.t.req('POST', path, { values })).json as unknown as SetupSaveResponse
  }
  async download(eol: 'unix' | 'win', serverDefault = '1'): Promise<string> {
    await this.t.req('POST', '/api/setup/config', {
      DefaultLang: 'en',
      ServerDefault: serverDefault,
      eol,
      action: 'download',
    })
    return (await this.t.req('GET', `/api/setup/config/download?eol=${eol}`)).text
  }
}

/** The posted fields of a BetterMyAdmin form set, as the browser sends the rendered form. */
function bmaPairs(fs: PrefsFormSet): Pairs {
  const out: Pairs = []
  for (const f of fs.forms)
    for (const i of f.items) {
      if (i.kind !== 'field') continue
      const x = i.field
      if (x.type === 'checkbox') {
        if (x.value === true) out.push([x.id, 'on'])
      } else if (x.type === 'select' && !(x.options ?? []).some((o) => o.value === x.value)) {
        // no option selected: the browser submits the first one
        out.push([x.id, x.options?.[0]?.value ?? ''])
      } else out.push([x.id, String(x.value)])
      if (x.userprefsAllow === true) out.push([`${x.id}-userprefs-allow`, 'on'])
    }
  return out
}

const fieldsOnly = (p: Pairs) =>
  p.filter(([k]) => !['tab_hash', 'check_page_refresh', 'token', 'server'].includes(k))

/** The generated file with what differs by design or by chance masked. */
function mask(php: string): string {
  return php
    .replace(/ \* Generated by: .* setup script/, ' * Generated by: PRODUCT setup script')
    .replace(/ \* Date: .*/, ' * Date: DATE')
    .replace(/sodium_hex2bin\('[0-9a-f]{64}'\)/, "sodium_hex2bin('SECRET')")
}

function pmaMessages(html: string): Msg[] {
  return [
    ...html.matchAll(
      /<div class="(error|notice)( hiddenmessage)?" id="([^"]+)">\s*<h4 class="fs-6">([\s\S]*?)<\/h4>([\s\S]*?)<\/div>/g,
    ),
  ].map((m) => ({
    id: m[3] as string,
    type: m[1] as 'error' | 'notice',
    title: visibleText(m[4] as string),
    hidden: m[2] !== undefined,
    text: visibleText(m[5] as string),
  }))
}
const bmaMessages = (o: SetupOverview): Msg[] =>
  o.messages.map((m) => ({
    id: m.id,
    type: m.type,
    title: visibleText(m.title),
    hidden: m.hidden,
    text: visibleText(m.message),
  }))

/** The system's missing compression functions differ (the reference PHP has no bz2 at all). */
const sameSystem = (list: Msg[]) =>
  list.map((m) => ({
    ...m,
    text: m.text.replace(/requires functions \([a-z, ]+\)/, 'requires functions (…)'),
  }))

/** The servers table rows: id, name, auth type, DSN. */
function pmaServers(html: string): string[][] {
  const table = html.match(/<table class="table w-auto datatable">([\s\S]*?)<\/table>/)?.[1] ?? ''
  return [
    ...table.matchAll(
      /<tr>\s*<td>([\s\S]*?)<\/td>\s*<td>([\s\S]*?)<\/td>\s*<td>([\s\S]*?)<\/td>\s*<td>([\s\S]*?)<\/td>/g,
    ),
  ].map((m) => [1, 2, 3, 4].map((i) => visibleText(m[i] as string)))
}
const bmaServers = (o: SetupOverview) => o.servers.map((s) => [String(s.id), s.name, s.authType, s.dsn])

/** The "Submitted form contains errors" list: (name, errors) per `dl`. */
function pmaErrorList(html: string): Array<{ name: string; errors: string[] }> {
  return [...html.matchAll(/<dl>\s*<dt>([\s\S]*?)<\/dt>([\s\S]*?)<\/dl>/g)].map((m) => ({
    name: visibleText(m[1] as string),
    errors: [...(m[2] as string).matchAll(/<dd>([\s\S]*?)<\/dd>/g)].map((d) => visibleText(d[1] as string)),
  }))
}

const SERVER_ADD = '/setup/index.php?route=/setup&page=servers&mode=add'
const serverEdit = (id: number) => `/setup/index.php?route=/setup&page=servers&mode=edit&id=${id}`

describe.skipIf(!available)('parity: setup script (src/Controllers/Setup, ConfigGenerator)', () => {
  beforeAll(async () => {
    root = await mysql.createConnection({ ...ROOT, multipleStatements: true })
    await root.query(`DROP USER IF EXISTS '${USER}'@'%'; CREATE USER '${USER}'@'%' IDENTIFIED BY '${USER}';`)
    inst = await startPmaInstance('', { noConfig: true })
  })
  afterAll(async () => {
    await root?.query(`DROP USER IF EXISTS '${USER}'@'%'`)
    await root?.end()
    await inst?.stop()
  })

  it('[p01-984896] a cookie server: same form fields, overview messages, servers and config.inc.php', async () => {
    const pc = new PmaClient(inst.url)
    const b = new BmaSetup()
    try {
      const [ph, bh] = [await pmaHome(pc), await b.home()]
      expect(sameSystem(bmaMessages(bh))).toEqual(sameSystem(pmaMessages(ph)))

      const pmaForm = await pmaFormPairs(pc, SERVER_ADD)
      const bmaForm = (await b.t.req('GET', '/api/setup/servers/0')).json.formSet as PrefsFormSet
      expect(bmaPairs(bmaForm)).toEqual(fieldsOnly(pmaForm))

      const pairs = setPair(setPair(pmaForm, 'Servers-0-host', ROOT.host), 'Servers-0-auth_type', 'cookie')
      await pmaSave(pc, SERVER_ADD, pairs)
      expect((await b.post('/api/setup/servers/0', pairs)).saved).toBe(true)

      const [ph2, bh2] = [await pmaHome(pc), await b.home()]
      expect(bmaServers(bh2)).toEqual(pmaServers(ph2))
      expect(sameSystem(bmaMessages(bh2))).toEqual(sameSystem(pmaMessages(ph2)))

      expect(mask(await b.download('unix'))).toBe(mask(await pmaDownload(pc, 'unix')))
    } finally {
      await b.t.close()
    }
  })

  it('[p01-984896] validateServer: a new server is not validated (Q62), an edited one is', async () => {
    const pc = new PmaClient(inst.url)
    const b = new BmaSetup()
    const errorsOf = (r: SetupSaveResponse) =>
      (r.errors ?? []).map((e) => ({ name: visibleText(e.name), errors: e.errors.map(visibleText) }))
    // the client address MySQL reports
    const strip = (l: Array<{ name: string; errors: string[] }>) =>
      l.map((e) => ({ ...e, errors: e.errors.map((x) => x.replace(/'@'[^']*'/, "'@'HOST'")) }))
    try {
      await pmaHome(pc)
      await b.home()
      const set = (pairs: Pairs, kv: string[][]) =>
        kv.reduce((acc, [k, v]) => setPair(acc, k as string, v as string), pairs)
      const bad = set(await pmaFormPairs(pc, SERVER_ADD), [
        ['Servers-0-host', ROOT.host],
        ['Servers-0-port', String(ROOT.port)],
        ['Servers-0-auth_type', 'config'],
        ['Servers-0-user', USER],
        ['Servers-0-password', 'wrong'],
      ])
      // FormDisplay::validate reads the values of `Servers/0/…` (nothing there): saved unchecked
      expect(pmaErrorList(await pmaSave(pc, SERVER_ADD, bad))).toEqual([])
      expect((await b.post('/api/setup/servers/0', bad)).saved).toBe(true)

      // editing server 1 validates its values: the connection test fails
      const edit = await pmaFormPairs(pc, serverEdit(1))
      const pe = pmaErrorList(await pmaSave(pc, serverEdit(1), edit))
      const be = await b.post('/api/setup/servers/1', edit)
      expect(be.saved).toBe(false)
      expect(strip(errorsOf(be))).toEqual(strip(pe))
      expect(pe[0]?.errors[0]).toMatch(
        /^Could not connect to the database server! - mysqli_connect\(\): \(HY000\/1045\)/,
      )

      const fixed = set(edit, [
        ['Servers-1-password', USER],
        ['Servers-1-AllowNoPassword', 'on'],
      ])
      expect(pmaErrorList(await pmaSave(pc, serverEdit(1), fixed))).toEqual([])
      expect((await b.post('/api/setup/servers/1', fixed)).saved).toBe(true)

      // a signon server without SignonURL, then edited
      const sso = set(await pmaFormPairs(pc, SERVER_ADD), [
        ['Servers-0-host', 'sso.example'],
        ['Servers-0-auth_type', 'signon'],
        ['Servers-0-SignonSession', 'SignonSession'],
      ])
      await pmaSave(pc, SERVER_ADD, sso)
      await b.post('/api/setup/servers/0', sso)
      const ssoEdit = await pmaFormPairs(pc, serverEdit(2))
      const pe2 = pmaErrorList(await pmaSave(pc, serverEdit(2), ssoEdit))
      const be2 = await b.post('/api/setup/servers/2', ssoEdit)
      expect(errorsOf(be2)).toEqual(pe2)
      expect(pe2.flatMap((e) => e.errors)).toContain(
        'Empty signon URL while using signon authentication method!',
      )

      // mode=revert puts the erroneous fields back to their defaults
      await pc.getPage('/setup/index.php?route=/setup&page=servers&mode=revert&id=2')
      await b.t.req('POST', '/api/setup/servers/2/revert', {})

      const [ph, bh] = [await pmaHome(pc), await b.home()]
      expect(bmaServers(bh)).toEqual(pmaServers(ph))
      expect(sameSystem(bmaMessages(bh))).toEqual(sameSystem(pmaMessages(ph)))
      expect(mask(await b.download('win', '2'))).toBe(mask(await pmaDownload(pc, 'win', '2')))
    } finally {
      await b.t.close()
    }
  })

  it('[p01-984896] Features form (security settings), TrustedProxies, deleting a server', async () => {
    const pc = new PmaClient(inst.url)
    const b = new BmaSetup()
    try {
      await pmaHome(pc)
      await b.home()
      for (const host of ['db1.example', 'db2.example']) {
        const add = setPair(await pmaFormPairs(pc, SERVER_ADD), 'Servers-0-host', host)
        await pmaSave(pc, SERVER_ADD, add)
        await b.post('/api/setup/servers/0', add)
      }
      const path = '/setup/index.php?route=/setup&page=form&formset=Features'
      const pmaForm = await pmaFormPairs(pc, path)
      const bmaForm = (await b.t.req('GET', '/api/setup/form/Features')).json.formSet as PrefsFormSet
      // the secret generated by the overview's checks is random on both sides
      const noSecret = (l: Pairs) =>
        l.map(([k, v]) => [k, k === 'blowfish_secret' ? 'SECRET' : v] as [string, string])
      expect(noSecret(bmaPairs(bmaForm))).toEqual(noSecret(fieldsOnly(pmaForm)))
      const changed = [
        ['AllowArbitraryServer', 'on'],
        ['LoginCookieValidity', '2000'],
        ['LoginCookieStore', '1000'],
        ['TrustedProxies', '1.2.3.4: HTTP_X_FORWARDED_FOR\nnot a proxy'],
        ['blowfish_secret', 'a-secret-of-exactly-32-bytes!!!!'],
        ['MaxDbList', '50'],
      ].reduce((acc, [k, v]) => setPair(acc, k as string, v as string), pmaForm)
      // NaturalOrder off: the posted checkbox is absent; users may not change MaxDbList
      const posted = changed.filter(([k]) => k !== 'NaturalOrder' && k !== 'MaxDbList-userprefs-allow')
      const pr = await pmaSave(pc, path, posted)
      const br = await b.post('/api/setup/form/Features', posted)
      expect(
        (br.errors ?? []).map((e) => ({ name: visibleText(e.name), errors: e.errors.map(visibleText) })),
      ).toEqual(pmaErrorList(pr))

      // delete server 1: server 2 becomes 1
      await pc.postPage('/setup/index.php?route=/setup&page=servers&mode=remove&id=1', {})
      await b.t.req('POST', '/api/setup/servers/1/delete', {})
      await b.home() // ServerDestroyController redirects to the overview

      const [ph, bh] = [await pmaHome(pc), await b.home()]
      expect(bmaServers(bh)).toEqual(pmaServers(ph))
      expect(sameSystem(bmaMessages(bh))).toEqual(sameSystem(pmaMessages(ph)))
      const [pf, bf] = [await pmaDownload(pc, 'unix'), await b.download('unix')]
      expect(bf).toContain("$cfg['blowfish_secret'] = \\sodium_hex2bin('")
      expect(mask(bf)).toBe(mask(pf))
      // a 32-byte secret is kept as is
      expect(bf).toBe(
        bf.replace(
          /sodium_hex2bin\('[0-9a-f]+'\)/,
          `sodium_hex2bin('${Buffer.from('a-secret-of-exactly-32-bytes!!!!').toString('hex')}')`,
        ),
      )
    } finally {
      await b.t.close()
    }
  })

  it('[p01-984896] the BetterMyAdmin configuration is the same $cfg read back', async () => {
    const b = new BmaSetup()
    try {
      await b.home()
      let add = bmaPairs((await b.t.req('GET', '/api/setup/servers/0')).json.formSet as PrefsFormSet)
      for (const [k, v] of [
        ['Servers-0-host', 'db.example'],
        ['Servers-0-auth_type', 'http'],
        ['Servers-0-auth_http_realm', 'Our DB'],
      ] as Pairs)
        add = setPair(add, k, v)
      expect((await b.post('/api/setup/servers/0', add)).saved).toBe(true)
      const cfg = (await b.t.req('GET', '/api/setup/config')).json as Json
      const json = JSON.parse(cfg.bma as string)
      expect(json.Servers['1']).toMatchObject({
        host: 'db.example',
        auth_type: 'http',
        auth_http_realm: 'Our DB',
      })
      expect(cfg.php).toContain("$cfg['Servers'][$i]['auth_http_realm'] = 'Our DB';")
    } finally {
      await b.t.close()
    }
  })
})
