/**
 * Golden parity of the setup script (docs/features/01 "Setup script"): the same form posts in a
 * phpMyAdmin instance without config.inc.php and in BetterMyAdmin; the generated config.inc.php
 * must be byte-identical (the date, the product/version line and a generated blowfish_secret
 * masked), and the overview messages, the server list and the error pages must match.
 * Only f01a_* users are created.
 */
